/**
 * React Native test shim for Vitest (plain-Node environment).
 *
 * Problem: react-native ships Flow-typed sources (`import typeof ...`,
 * `} as T` casts) that Metro strips at bundle time but plain Node cannot
 * parse, and its components eagerly touch native modules that do not exist
 * outside a device/simulator. Jest solves this with @react-native/jest-preset
 * (module mocks + babel); Vitest has no equivalent.
 *
 * Fix (zero new dependencies — everything used is already in the tree):
 * 1. Pre-bundle react-native with rolldown (vite 8's bundler), stripping
 *    Flow via the same Hermes-parser + flow babel plugins that
 *    @react-native/babel-preset uses, with Metro-style platform file
 *    resolution (`.ios.js` → `.native.js` → `.js`, ios platform like the
 *    RN jest preset).
 * 2. Inside the bundle, redirect the exact module paths the official jest
 *    preset mocks (ScrollView, Text, View, NativeComponentRegistry,
 *    UIManager, requireNativeComponent, NativeModules, InitializeCore) to
 *    jest-free equivalents — mirroring
 *    @react-native/jest-preset@0.86.2 jest/setup.js.
 * 3. Seed Node's `require.cache` for react-native's resolved id with the
 *    pre-bundled exports BEFORE any test imports run (setupFiles). Both
 *    the Vitest module graph (through a lazy facade alias) and native CJS
 *    requires (RNTL's) share one module instance — identity matters: RNTL
 *    must see the same components the screens under test render.
 *
 * The bundle is cached on disk keyed by the react-native version plus the
 * shim implementation version.
 */

const SHIM_VERSION = "2";
const RN_PLATFORM = "ios"; // matches the react-native jest preset default

const nodeRequire = createRequire(import.meta.url);
const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const cacheDir = path.join(projectRoot, "node_modules/.cache/lemastra-vitest-rn");

export async function installReactNativeTestShim(): Promise<void> {
  const rnPackageId = nodeRequire.resolve("react-native/package.json");
  const rnRoot = path.dirname(rnPackageId);
  const rnVersion: string = JSON.parse(fsSync.readFileSync(rnPackageId, "utf8")).version;
  const bundlePath = path.join(cacheDir, `react-native-${rnVersion}-shim${SHIM_VERSION}.cjs`);

  const rnId = nodeRequire.resolve("react-native");
  if (nodeRequire.cache[rnId]) {
    // Already loaded (e.g. a second setup pass in the same worker).
    return;
  }

  if (!fsSync.existsSync(bundlePath)) {
    fsSync.mkdirSync(cacheDir, { recursive: true });
    await buildRnBundle(path.join(rnRoot, "index.js"), rnRoot, bundlePath);
  }
  fsSync.writeFileSync(facadePath(), lazyFacadeSource(rnId), "utf8");

  // Globals shaped after @react-native/jest-preset jest/setup.js.
  const g = globalThis as Record<string, unknown>;
  if (typeof g.__turboModuleProxy !== "function") {
    g.__turboModuleProxy = (name: string): unknown => turboModuleMock(name);
  }
  if (g.nativeModuleProxy === undefined || g.nativeModuleProxy === null) {
    g.nativeModuleProxy = {};
  }
  if (typeof g.ErrorUtils === "undefined" || g.ErrorUtils === null) {
    g.ErrorUtils = {
      setGlobalHandler: () => undefined,
      getGlobalHandler: () => undefined,
      reportFatalError: (error: unknown) => {
        throw error;
      },
      reportError: () => undefined,
    };
  }
  // The Fabric renderer reads this bare global at module scope; the jest
  // preset provides a plain empty object.
  if (g.nativeFabricUIManager === undefined || g.nativeFabricUIManager === null) {
    g.nativeFabricUIManager = {};
  }
  if (g.IS_REACT_NATIVE_TEST_ENVIRONMENT === undefined) {
    g.IS_REACT_NATIVE_TEST_ENVIRONMENT = true;
  }
  if (g.window === undefined) {
    g.window = globalThis;
  }

  const mod = new Module(rnId);
  mod.filename = rnId;
  mod.exports = nodeRequire(bundlePath);
  mod.loaded = true;
  nodeRequire.cache[rnId] = mod;
}

/**
 * Facade aliased in for bare `react-native` imports (vitest.config.ts
 * writes the same file at config time). LAZY on purpose: modules importing
 * react-native may be collected BEFORE the setupFile seeds require.cache,
 * so the facade must not touch the raw package at import time — only on
 * first property access, which happens at render time (post-setup).
 */
export function lazyFacadeSource(rnId: string): string {
  return [
    `// Generated by scripts/vitest/react-native-shim.ts — do not edit.`,
    `module.exports = new Proxy({}, {`,
    `  get(_target, prop) {`,
    `    if (prop === "__esModule") return false;`,
    `    if (prop === "then" || prop === "toJSON") return undefined;`,
    `    const rn = require(${JSON.stringify(rnId)});`,
    `    const value = rn[prop];`,
    `    return typeof value === "function" ? value.bind(rn) : value;`,
    `  },`,
    `});`,
    ``,
  ].join("\n");
}

function facadePath(): string {
  return path.join(cacheDir, "rn-require-facade.cjs");
}

