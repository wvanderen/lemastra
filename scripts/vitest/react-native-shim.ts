/**
 * A no-op native module: every property is a function returning
 * undefined. Crucial for feature flags — RN flag getters do
 * `nativeFlagModule[name]?.() ?? defaultValue`, so undefined results keep
 * every experimental path at its JS default.
 */
function makeNoopNativeModule(): unknown {
  return new Proxy(
    {},
    {
      get(_target, prop) {
        if (typeof prop === "symbol") return undefined;
        if (prop === "then" || prop === "toJSON") return undefined;
        return () => undefined;
      },
    }
  );
}

